export function applyLanguage(next = language) {
  if (!Object.hasOwn(messages, next)) return;
  language = next;
  try {
    localStorage.setItem('reservet.language', language);
  } catch {
    /* Optional preference. */
  }
  document.documentElement.lang = language;
  document.querySelector('#language').value = language;
  for (const [selector, key, attribute] of bindings) {
    const element = document.querySelector(selector);
    if (attribute) element.setAttribute(attribute, t(key));
    else {
      const text = [...element.childNodes].find(
        (node) => node.nodeType === 3 && node.textContent.trim(),
      );
      if (text) text.textContent = ` ${t(key)} `;
      else element.prepend(document.createTextNode(t(key)));
    }
  }
}
